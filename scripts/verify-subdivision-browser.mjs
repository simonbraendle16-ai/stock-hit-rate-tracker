// Fallback after repeated CUA/CDP timeouts. Isolated headless browser, loopback only.
import {createRequire} from 'node:module';
import {join,resolve} from 'node:path';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
import pg from 'pg';
const requireTool=createRequire(join(process.env.APPDATA,'npm/node_modules/browser-use/package.json'));
const {chromium}=requireTool('playwright');
const out=resolve('docs/subdivision-qa');await mkdir(out,{recursive:true});
const report=JSON.parse(await readFile(join(out,'local-api.json'),'utf8'));
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1050}});
page.setDefaultTimeout(20000);
const client=new pg.Client({connectionString:'postgresql://postgres:postgres@127.0.0.1:5561/postgres'});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
page.on('response',r=>{if(r.status()>=500)errors.push(`HTTP ${r.status()} ${new URL(r.url()).pathname}`);});
const select=async(label,value,scope=page)=>{await scope.getByRole('combobox',{name:label,exact:true}).click();await page.getByRole('option',{name:value,exact:true}).click();};
try {
 await client.connect();
 const initial=(await client.query('SELECT evidence,version FROM fibonacci_observation WHERE id=$1',[report.editableId])).rows[0];
 const initialLabel=initial.evidence.subdivision==='five_part' ? 'Fünfteilig' : 'Dreiteilig';
 const auth=await page.context().request.post('http://localhost:3041/api/auth/sign-in/email',{headers:{Origin:'http://localhost:3041'},data:{email:'fibonacci-qa@example.invalid',password:'Local-Fibonacci-QA-2026!'}});
 assert.equal(auth.status(),200);console.log('Synthetic local authentication succeeded');
 await page.goto('http://localhost:3041/analysis?fib.detail='+report.editableId);
 const detail=page.getByRole('dialog');await detail.waitFor({state:'visible',timeout:30000});
 assert.ok((await detail.innerText()).includes(initialLabel));
 await detail.getByRole('button',{name:'Zurück zur Auswahl',exact:true}).click();
 await page.getByRole('row').filter({hasText:report.editableId}).getByRole('button',{name:/bearbeiten/i}).click();
 const form=page.getByRole('dialog');
 assert.equal(await form.getByRole('combobox',{name:'Innere Unterteilung',exact:true}).innerText(),initialLabel);
 await select('Innere Unterteilung','Dreiteilig',form);
 await select('Sicherheit der Unterteilung','Bestätigt',form);
 await form.screenshot({path:join(out,'desktop-final.png')});
 await form.getByRole('button',{name:/speichern/i}).click();
 await page.getByText('Gespeichert und zurückgelesen.',{exact:true}).waitFor({state:'visible',timeout:30000});
 const stored=(await client.query('SELECT evidence,version FROM fibonacci_observation WHERE id=$1',[report.editableId])).rows[0];
 assert.equal(stored.version,initial.version+1);assert.equal(stored.evidence.subdivision,'three_part');assert.equal(stored.evidence.subdivisionConfidence,'bestaetigt');
 await select('Innere Unterteilung','Dreiteilig');await select('Sicherheit der Unterteilung','Bestätigt');
 await page.getByText('Innere Unterteilung · getrennt vom Muster',{exact:true}).waitFor({state:'visible'});
 await page.locator('#fibonacci').screenshot({path:join(out,'results-desktop.png')});
 assert.ok(page.url().includes('fib.subdivision=three_part'));
 await page.getByRole('button',{name:'Neue Beobachtung',exact:true}).click();
 assert.equal(await form.getByRole('combobox',{name:'Innere Unterteilung',exact:true}).innerText(),'Dreiteilig');
 await page.setViewportSize({width:390,height:844});
 await form.screenshot({path:join(out,'mobile-final.png')});
 const size=await form.evaluate(e=>({client:e.clientWidth,scroll:e.scrollWidth}));
 assert.ok(size.scroll<=size.client+1,JSON.stringify(size));
 await form.getByRole('button',{name:'Abbrechen',exact:true}).click();
 assert.deepEqual(errors,[]);
 const result={checkedAt:new Date().toISOString(),syntheticOnly:true,fallbackReason:'CUA CDP focus/evaluate timeouts and lost tab association',desktop:{width:1440},mobile:{width:390,...size},savedAndReadBack:true,version:stored.version,filterUrl:true,filteredFormDefault:true,resultsVisible:true,pageErrors:errors};
 await writeFile(join(out,'browser.json'),JSON.stringify(result,null,2)+'\n');console.log(JSON.stringify(result));
}catch(error){console.error(JSON.stringify({url:page.url(),errors}));await page.screenshot({path:join(out,'browser-failure.png'),timeout:5000}).catch(()=>{});throw error;}finally{await client.end();await browser.close();}
